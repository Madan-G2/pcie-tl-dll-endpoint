#!/usr/bin/env python3
"""scripts/plot_results.py : plots for spec 8.5 from results/csv/perf.csv -> results/plots/*.png and results/csv/summary.md
Every row is one run; points are the mean over seeds with min / max error bars. Run with a Python that has matplotlib
(on the lab machines: /apps/miniconda/bin/python3 scripts/plot_results.py)."""
import csv, os, statistics as st
from collections import defaultdict
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CSV = os.path.join(ROOT, "results", "csv", "perf.csv")
OUT = os.path.join(ROOT, "results", "plots")
os.makedirs(OUT, exist_ok=True)
# mode = OPT_CTRL value: 0 baseline, the optimization's own bits, 63 (0x3F) everything on
COL  = {0: "#5b6b7f", 7: "#2a9d8f", 8: "#2a9d8f", 16: "#2a9d8f", 32: "#2a9d8f", 63: "#d9822b"}
NAME = {0: "baseline", 7: "OP1 only (0x07)", 8: "OP2 only (0x08)", 16: "OP3 only (0x10)", 32: "OP4 only (0x20)", 63: "all optimizations (0x3F)"}
MODES = {"W1a": (0, 7, 63), "W1b": (0, 7, 63), "W1c": (0, 7, 63), "W2": (0, 8, 63), "W3a": (0, 16, 63), "W4": (0, 32, 63)}

rows = [r for r in csv.reader(open(CSV)) if r]
def num(x):
    try: return float(x)
    except ValueError: return x

# group : key -> list of metric values over seeds
def collect(wl, keyf, valf):
    g = defaultdict(list)
    for r in rows:
        if r[0] != wl: continue
        v = [num(x) for x in r]
        g[keyf(v)].append(valf(v))
    return g
def seeds(wl):
    return sorted({int(r[4]) for r in rows if r[0] == wl})
def mmm(v): return st.mean(v), min(v), max(v)

def errplot(ax, xs, g, k_of, label, color, marker="o", ls="-"):
    pts = [(x, mmm(g[k_of(x)])) for x in xs if k_of(x) in g]
    if not pts: return
    x = [p[0] for p in pts]; m = [p[1][0] for p in pts]
    lo = [p[1][0] - p[1][1] for p in pts]; hi = [p[1][2] - p[1][0] for p in pts]
    ax.errorbar(x, m, yerr=[lo, hi], label=label, color=color, marker=marker, ls=ls, capsize=3, lw=1.6, ms=5)

def caption(fig, text):
    fig.text(0.01, 0.01, text, fontsize=7.5, color="#444", ha="left", va="bottom", wrap=True)

summary = ["# Performance summary (generated by scripts/plot_results.py)\n"]

# ---------------------------------------------------------------- OP1 : W1a / W1b goodput vs error rate
PPM = [0, 100, 1000, 10000, 50000]
xpos = {p: i for i, p in enumerate(PPM)}
for wl, size in (("W1a", 128), ("W1b", 16)):
    g = collect(wl, lambda v: (int(v[1]), int(v[3]), int(v[2])), lambda v: v[9])
    if not g: continue
    fig, axs = plt.subplots(1, 2, figsize=(10, 4.2), sharey=True)
    for ax, lat in zip(axs, (8, 32)):
        for o in MODES[wl]:
            errplot(ax, PPM, g, lambda p: (o, lat, p), NAME[o], COL[o], ls="--" if o == 63 else "-")
        ax.set_xscale("symlog", linthresh=100); ax.set_xticks(PPM); ax.set_xticklabels(["0", "100", "1k", "10k", "50k"])
        ax.set_title(f"LINK_LATENCY = {lat}"); ax.set_xlabel("CORRUPT_BIT rate on A->B TLPs (ppm)"); ax.grid(alpha=.3)
    axs[0].set_ylabel("goodput (delivered bytes / cycle)"); axs[0].legend()
    fig.suptitle(f"OP1 {wl}: A streams 2,000 x {size}-byte AXI writes to B (spec 8.1)")
    caption(fig, f"clk 4 ns; OPT_CTRL 0x00 / 0x07 / 0x3F; ACK_CFG reset values (N=4, timer 32, hold 16); "
                 f"REPLAY_CFG win 8 / timeout 1024; seeds {seeds(wl)}; mean with min/max.")
    fig.tight_layout(rect=(0, .05, 1, 1)); fig.savefig(os.path.join(OUT, f"op1_{wl.lower()}_goodput.png"), dpi=130); plt.close(fig)
    summary.append(f"## {wl} goodput (B/cycle), mean over seeds {seeds(wl)}\n\n| lat | ppm | baseline | OP1 only | gain | all on | gain |\n|---|---|---|---|---|---|---|")
    for lat in (8, 32):
        for p in PPM:
            if all((o, lat, p) in g for o in MODES[wl]):
                b, o1, oa = (st.mean(g[(o, lat, p)]) for o in MODES[wl])
                summary.append(f"| {lat} | {p} | {b:.2f} | {o1:.2f} | {100 * (o1 / b - 1):+.1f}% | {oa:.2f} | {100 * (oa / b - 1):+.1f}% |")
    summary.append("")

# ---------------------------------------------------------------- OP1 : W1c tail-loss recovery
g = collect("W1c", lambda v: (int(v[1]), int(v[3])), lambda v: v[16])
if g:
    fig, ax = plt.subplots(figsize=(6, 4))
    lats = sorted({k[1] for k in g}); w = 0.27
    for j, o in enumerate(MODES["W1c"]):
        m = [st.mean(g[(o, l)]) if (o, l) in g else 0 for l in lats]
        lo = [m[i] - min(g[(o, l)]) for i, l in enumerate(lats)]; hi = [max(g[(o, l)]) - m[i] for i, l in enumerate(lats)]
        ax.bar([i + (j - 1) * w for i in range(len(lats))], m, w, yerr=[lo, hi], capsize=3, color=COL[o], label=NAME[o], hatch="//" if o == 63 else None)
        for i, v in enumerate(m): ax.text(i + (j - 1) * w, v + 15, f"{v:.0f}", ha="center", fontsize=8)
    ax.set_xticks(range(len(lats))); ax.set_xticklabels([f"LINK_LATENCY {l}" for l in lats])
    ax.set_ylabel("cycles from the last write's AW to its delivery"); ax.grid(axis="y", alpha=.3); ax.legend()
    ax.set_title("OP1 W1c: last TLP of a 16-write burst dropped, then silence")
    caption(fig, f"baseline recovers by REPLAY_CFG.TIMEOUT_CYC (1024); optimized by the adaptive timer (OP1-4); seeds {seeds('W1c')}")
    fig.tight_layout(rect=(0, .06, 1, 1)); fig.savefig(os.path.join(OUT, "op1_w1c_tail_loss.png"), dpi=130); plt.close(fig)
    summary.append("## W1c tail-loss recovery (cycles)\n\n| lat | baseline | OP1 only | all on |\n|---|---|---|---|")
    for l in lats: summary.append(f"| {l} | " + " | ".join(f"{st.mean(g[(o, l)]):.0f}" for o in MODES["W1c"]) + " |")
    summary.append("")

# ---------------------------------------------------------------- OP2 : W2 credit starvation
gu = collect("W2", lambda v: (int(v[1]), int(v[3]), int(v[6])), lambda v: v[10])
gs = collect("W2", lambda v: (int(v[1]), int(v[3]), int(v[6])), lambda v: v[11])
if gu:
    UP = sorted({k[2] for k in gu})
    fig, axs = plt.subplots(1, 2, figsize=(10, 4.2))
    for lat, ls in ((8, "-"), (32, "--")):
        for o in MODES["W2"]:
            mk = {0: "o", 8: "s", 63: "^"}[o]
            errplot(axs[0], UP, gu, lambda u: (o, lat, u), f"{NAME[o]}, lat {lat}", COL[o], ls=ls, marker=mk)
            errplot(axs[1], UP, gs, lambda u: (o, lat, u), f"{NAME[o]}, lat {lat}", COL[o], ls=ls, marker=mk)
    for ax in axs: ax.set_xscale("log"); ax.set_xlabel("FC_CFG.UPDATEFC_TIMER_CYC (cycles)"); ax.grid(alpha=.3)
    axs[0].set_ylabel("link utilization (TLP beats / cycle)"); axs[1].set_ylabel("CNT_TX_STALL_CREDIT (cycles)")
    axs[0].legend(fontsize=8)
    fig.suptitle("OP2 W2: 1,500 x 16-byte writes, P credits 32 hdr / 128 data, slow UpdateFC")
    caption(fig, "independent variable is the UpdateFC period instead of P_HDR_CR (a build parameter); OP2 = FC_EARLY_UPDATE_EN "
                 f"(thresholds 8 hdr / 32 data, max delay 32); seeds {seeds('W2')}")
    fig.tight_layout(rect=(0, .06, 1, 1)); fig.savefig(os.path.join(OUT, "op2_w2_credits.png"), dpi=130); plt.close(fig)
    summary.append("## W2 credit starvation, LINK_LATENCY 8\n\n| UpdateFC period | util base | util OP2 only | util all on | stall base | stall OP2 only | stall all on |\n|---|---|---|---|---|---|---|")
    for u in UP:
        if all((o, 8, u) in gu for o in MODES["W2"]):
            summary.append(f"| {u} | " + " | ".join(f"{st.mean(gu[(o, 8, u)]):.3f}" for o in MODES["W2"]) + " | " + " | ".join(f"{st.mean(gs[(o, 8, u)]):.0f}" for o in MODES["W2"]) + " |")
    summary.append("")

# ---------------------------------------------------------------- OP3 : W3a link efficiency vs write size
g = collect("W3a", lambda v: (int(v[1]), int(v[6])), lambda v: v[10])
if g:
    SZ = sorted({k[1] for k in g})
    ana = {4: 12.5, 8: 25.0, 16: 33.3, 32: 50.0, 64: 66.7, 128: 80.0}
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    for o in MODES["W3a"]:
        gp = {k: [100 * x for x in v] for k, v in g.items()}
        errplot(ax, SZ, gp, lambda s: (o, s), NAME[o], COL[o], ls="--" if o == 63 else "-")
    ax.plot(list(ana), list(ana.values()), "k:", marker="x", label="analytic table (spec 8.3)")
    ax.set_xscale("log", base=2); ax.set_xticks(SZ); ax.set_xticklabels([str(s) for s in SZ])
    ax.set_xlabel("AXI write size (bytes), sequential addresses"); ax.set_ylabel("link efficiency (%) = payload / (16 x TLP beats)")
    ax.grid(alpha=.3); ax.legend(); ax.set_title("OP3 W3a: small-write coalescing")
    caption(fig, f"1,000 writes per point; optimized = WR_COALESCE_EN (COAL_TIMEOUT 16, MPS 256); seeds {seeds('W3a')}")
    fig.tight_layout(rect=(0, .06, 1, 1)); fig.savefig(os.path.join(OUT, "op3_w3a_efficiency.png"), dpi=130); plt.close(fig)
    summary.append("## W3a link efficiency (%)\n\n| size | analytic | baseline | OP3 only | all on |\n|---|---|---|---|---|")
    for s in SZ: summary.append(f"| {s} | {ana.get(s, 0):.1f} | " + " | ".join(f"{100 * st.mean(g[(o, s)]):.1f}" for o in MODES["W3a"]) + " |")
    summary.append("")

# ---------------------------------------------------------------- OP4 : W4 read latency p99 vs slow fraction
g99 = collect("W4", lambda v: (int(v[1]), int(v[6]), int(v[7])), lambda v: v[9])
g50 = collect("W4", lambda v: (int(v[1]), int(v[6]), int(v[7])), lambda v: v[8])
if g99:
    SL = sorted({k[2] for k in g99 if k[1] != 1})
    fig, axs = plt.subplots(1, 2, figsize=(10, 4.2))
    for o in MODES["W4"]:
        errplot(axs[0], SL, g50, lambda s: (o, 8, s), NAME[o], COL[o], ls="--" if o == 63 else "-")
        errplot(axs[1], SL, g99, lambda s: (o, 8, s), NAME[o], COL[o], ls="--" if o == 63 else "-")
        if (o, 1, 20) in g99 and o != 63:
            axs[1].plot([20], [st.mean(g99[(o, 1, 20)])], marker="s", color=COL[o], ls="none", ms=8, mfc="none",
                        label=f"{NAME[o]}, single AXI ID (control)")
    axs[0].set_ylabel("read latency p50 (cycles)"); axs[1].set_ylabel("read latency p99 (cycles)")
    for ax in axs: ax.set_xlabel("slow memory reads at B (%), slow = 300 cycles, fast = 2"); ax.grid(alpha=.3)
    axs[1].legend(fontsize=8)
    fig.suptitle("OP4 W4: 400 x 64-byte reads from A, 8 AXI IDs, up to 12 in flight")
    caption(fig, f"optimized = RD_OOO_EN (completions returned per ID out of order); B memory answers out of order; seeds {seeds('W4')}")
    fig.tight_layout(rect=(0, .06, 1, 1)); fig.savefig(os.path.join(OUT, "op4_w4_read_latency.png"), dpi=130); plt.close(fig)
    summary.append("## W4 read latency (cycles), 8 IDs\n\n| slow % | p50 base | p50 OP4 only | p50 all on | p99 base | p99 OP4 only | p99 all on |\n|---|---|---|---|---|---|---|")
    for s in SL: summary.append(f"| {s} | " + " | ".join(f"{st.mean(g50[(o, 8, s)]):.0f}" for o in MODES["W4"]) + " | " + " | ".join(f"{st.mean(g99[(o, 8, s)]):.0f}" for o in MODES["W4"]) + " |")
    if all((o, 1, 20) in g99 for o in MODES["W4"]):
        summary.append("| control (1 ID, 20%) | " + " | ".join(f"{st.mean(g50[(o, 1, 20)]):.0f}" for o in MODES["W4"]) + " | " + " | ".join(f"{st.mean(g99[(o, 1, 20)]):.0f}" for o in MODES["W4"]) + " |")
    summary.append("")

open(os.path.join(ROOT, "results", "csv", "summary.md"), "w").write("\n".join(summary) + "\n")
print("plots:", sorted(os.listdir(OUT)))
